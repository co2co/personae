"""叙事正文净身：剥离模型倒进可见正文的元信息（兜底网）。

模型有时会把系统提示里的「创作铁律 / 输出纪律」演绎成工作笔记，在正文里输出安全前言、
铁律复述、策略调整 / 推演执行 / 后果留痕 / 下一回合预览等元标题，污染叙事。

本模块做防御性净身：删元信息，保留叙事正文。主手段是 prompter 的「输出纪律」约束
（不让模型产出这些），此处仅为兜底，处理提示词未能压住时的漏网。

设计原则：
- 只删「高度可判定为元信息」的行/块，正常叙事尽量原样通过（零误伤优先）。
- 只删整行元标题与尾部整段，不做整句正则删除（2026-11-08 瘦身，见下）。
- 最后压缩多余空行。

2026-11-08 引擎瘦身删掉的整句正则（回滚：
git checkout checkpoint-pre-slim-20261108 -- engine/narrative_clean.py）：
「我将以…规避/克制/留白…」、「鉴于…我将…规避…」。它们清的是几代以前系统提示词的
失败形态：现行提示词从不谈「规避 / 克制」，模型照抄的对象已不存在；而「我将」「鉴于」
是台词里会正常出现的开头，整句删除会连对白一起吞掉。「场景[：:]」元标题同理（正文以
「场景：」起句会被误删），已移出元标题表。行首编号列举（「1. 」开头即删）一并撤除：
它没有锚点，正常叙事里的编号行也会被吞。
「关系推演沙盘的导演引擎」自居句保留：这个措辞出现在正文里必然是元信息，零误伤。
"""

import re

# 整行删除：元信息标题行（允许前导空格 / 单个或成对星号 / 方括号）
# 刻意不以 \b 收尾（2026-11-15 移植 nsfw 线实测修正）：Python 的 \w 认中文，
# 「我无法」后面紧跟「执」这类汉字时词边界不成立，旧模式对
# 「我无法执行该请求。」整句匹配失败——真实拒答前言原样落进正文与历史。
# 去掉 \b 后同一条规则也收住中文程度副词变体（很/非常/实在/真/十分抱歉）与「我不能」。
# 误伤面：仅行首且前缀只允许空格 / 星号 / 方括号，中文引号开头的台词（「抱歉，…」「“我不能…”」）
# 不在匹配范围内，由 tests/test_narrative_clean.py 锁住。
_META_HEADER_RE = re.compile(
    r"^\s*(?:【?\*?\*?)?(?:"
    r"警告|安全准则|根据系统安全|作为\s*AI|我作为\s*AI|(?:很|非常|实在|真|十分)?抱歉[，,]|"
    r"我无法|我不能|"
    r"策略调整|推演执行|环境推手注入的扰动已兑现|关系改写|"
    r"铁律\d|当前的局势是|当前局势是|局势是|"
    r"在场角色|本回合在场角色"
    r")"
)

# 尾部摘要段：遇到这些标题，从该标题行起整段（到文末）删除
_TRAILING_CUTOFF_RE = re.compile(
    r"^\s*(?:【?\*?\*?)?(?:后果留痕|下一回合预览|下一轮预览|关系改写|注意[：:])\b"
)


# 模型以「导演引擎」自居并自我说明的整句。只锁这一个老措辞：它出现在正文里必然是元信息
# （对白不会自称「关系推演沙盘的导演引擎」），零误伤；而「我将 / 鉴于」式整句删除会连
# 台词一起吞掉，已撤。
_DIRECTOR_ENGINE_RE = re.compile(r"[^。\n]*?关系推演沙盘的导演引擎[^。\n]*?[。\n]")

# 模型插入的元信息分隔线（*** / ---）
_HR_RE = re.compile(r"\n\s*\*{3,}\s*\n|\n\s*-{3,}\s*\n")


def clean_narrative(text):
    """返回净身后的叙事正文。空输入原样返回。"""
    if not text:
        return text
    lines = text.split("\n")
    out = []
    dropped_tail = False
    for line in lines:
        if dropped_tail:
            continue
        # 尾部摘要截断（后果留痕 / 下一回合预览 / 关系改写 / 注意）
        if _TRAILING_CUTOFF_RE.match(line):
            dropped_tail = True
            continue
        # 整行元标题 / 导演注释行
        if _META_HEADER_RE.match(line):
            continue
        out.append(line)
    cleaned = "\n".join(out)
    cleaned = _DIRECTOR_ENGINE_RE.sub("", cleaned)
    # 元信息分隔线
    cleaned = _HR_RE.sub("\n\n", cleaned)
    # 压缩连续空行（>2 压成 1）并去掉首尾空白
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned).strip()
    return cleaned
